SUBJECT_CATEGORIES = {
    "상담이론 및 실제": "전공",
    "집단상담": "전공",
    "진로상담": "전공",
    "이상심리학": "전공",
    "발달심리학": "전공",
    "학교상담": "전공",
    "심리측정 및 평가": "전공",
    "학습심리학": "전공",
}


def get_or_create_subject(cursor, name):
    category = SUBJECT_CATEGORIES.get(name, "전공")
    cursor.execute("SELECT id FROM Subject WHERE name = ?", (name,))
    row = cursor.fetchone()
    if row:
        return row[0], False
    cursor.execute(
        "INSERT INTO Subject (name, category) VALUES (?, ?)",
        (name, category)
    )
    return cursor.lastrowid, True


def get_or_create_topic(cursor, name, subject_id):
    cursor.execute(
        "SELECT id FROM Topic WHERE name = ? AND subjectId = ?",
        (name, subject_id)
    )
    row = cursor.fetchone()
    if row:
        return row[0], False
    cursor.execute(
        "INSERT INTO Topic (name, subjectId) VALUES (?, ?)",
        (name, subject_id)
    )
    return cursor.lastrowid, True


def main():
    db_path = os.path.abspath(DB_PATH)
    print(f"Connecting to database: {db_path}")

    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()

    subjects_created = 0
    topics_created = 0
    questions_imported = 0
    questions_skipped = 0

    for q in PAST_EXAM_QUESTIONS:
        subject_name = q["subject"]
        topic_name = q["topic"]
        year = q["year"]
        page_ref = f"{year} 기출"

        subject_id, s_new = get_or_create_subject(cursor, subject_name)
        if s_new:
            subjects_created += 1
            print(f"  Created subject: {subject_name}")

        topic_id, t_new = get_or_create_topic(cursor, topic_name, subject_id)
        if t_new:
            topics_created += 1
            print(f"  Created topic: {topic_name} (subject: {subject_name})")

        # Check for duplicate question by content
        cursor.execute(
            "SELECT id FROM Question WHERE content = ? AND source = 'past_exam'",
            (q["content"],)
        )
        if cursor.fetchone():
            print(f"  SKIP (already exists): {year} - {topic_name}")
            questions_skipped += 1
            continue

        cursor.execute(
            """
            INSERT INTO Question (content, modelAnswer, type, source, difficulty, pageRef, subjectId, topicId)
            VALUES (?, ?, 'essay', 'past_exam', 4, ?, ?, ?)
            """,
            (q["content"], q["modelAnswer"], page_ref, subject_id, topic_id)
        )
        questions_imported += 1
        print(f"  Imported: {year} - {topic_name}")

    conn.commit()
    conn.close()

    print()
    print("=" * 50)
    print("Import Summary")
    print("=" * 50)
    print(f"  Subjects created : {subjects_created}")
    print(f"  Topics created   : {topics_created}")
    print(f"  Questions imported: {questions_imported}")
    print(f"  Questions skipped : {questions_skipped}")
    print(f"  Total processed  : {questions_imported + questions_skipped}")
    print("=" * 50)


if __name__ == "__main__":
    main()
